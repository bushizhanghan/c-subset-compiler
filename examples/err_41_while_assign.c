/* err_41_while_assign.c
 * ---------------------------------------------------------------
 * 错误：while 的条件里用了赋值 =，应该用相等比较 ==。
 * 为什么错（教材概念）：C 里 = 是赋值运算符，它有值（赋进去的那个值），
 *   所以 `while (x = 1)` 语法合法、类型也对（int 就是条件类型）。
 *   但它每个轮次都先把 1 赋给 x，再拿 1 当条件——恒为真，循环永不结束，
 *   而且 x 的原本取值被彻底覆盖，连"条件判断"这个意图都没有了。
 *   教材在"关系运算符与逻辑运算符"一节明确要求：
 *   `==` 是比较，`=` 是赋值，写错不会报错但语义完全变了。
 * 为什么和 err_19 分开：err_19 是 `if (x = 10)`，本用例是 `while (...)`，
 *   两条语句走的检查分支不同（条件检查 vs 循环条件检查），
 *   而且 while 里的误写后果更严重——直接变成死循环。
 * 后果：能编译（gcc 要 -Wall 才给 -Wparentheses 警告），运行时卡死。
 * 期望 csub 报什么：W5 while 的条件里用了赋值 =，通常是想写比较 ==。
 * 期望码：W5
 * 分类：逻辑错误
 * ---------------------------------------------------------------
 */
int main() {
    int x = 3;
    int y = 0;
    while (x = 1) {              /* ← 错在这：应为 while (x == 1) */
        y = y + 1;
        if (y > 3) {
            break;               /* 只加这个 break 才不至于真的卡死 */
        }
    }
    printf("%d %d\n", x, y);
    return 0;
}
