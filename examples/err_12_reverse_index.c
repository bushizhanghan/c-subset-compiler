/* err_12_reverse_index.c
 * ---------------------------------------------------------------
 * 错误：数组倒序输出的循环写成 i-- 从 0 开始，下标越界。
 * 为什么错（教材概念）：倒序遍历的起点应是最后一个元素 n-1，
 *   终止条件是 i >= 0。这里把起点写成了 0、增量写成 i--，
 *   第一次访问就是 arr[-1]。
 * 后果：读到数组前一块内存的垃圾值，输出不可预测。
 * 期望 csub 报什么：E13 数组下标越界（负下标）。
 *   csub 的 E13 只查常量下标，这里 i 是变量，预期漏报；
 *   但如果循环被展开成常量下标，则可能检出。
 * ---------------------------------------------------------------
 */
#include <stdio.h>
int main() {
    int arr[5] = {10, 20, 30, 40, 50};
    int i;
    for (i = 0; i >= 0; i--) {    /* ← 错在这：应为 for (i = 4; i >= 0; i--) */
        printf("%d\n", arr[i]);   /* 第一次就是 arr[-1] */
    }
    return 0;
}
