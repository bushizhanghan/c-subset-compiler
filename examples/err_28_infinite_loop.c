/* err_28_infinite_loop.c
 * ---------------------------------------------------------------
 * 错误：for 循环的增量方向写反，循环变量越走越远，永远不满足
 *   退出条件。
 * 为什么错（教材概念）：for 的三个表达式必须"朝着退出条件的
 *   方向走"：条件要 i < 10，增量就得是 i++；写 i-- 时 i 只会
 *   越来越小，永远到不了 10。这是死循环第二常见的成因。
 * 后果：程序卡死。
 * 期望 csub 报什么：一条"循环变量朝远离条件的方向变化"的警告。
 *   目前 csub 没有这条检查，预期漏报。
 * ---------------------------------------------------------------
 */
int main() {
    int i;
    for (i = 0; i < 10; i--) {    /* ← 错在这：i-- 应为 i++ */
        printf("%d\n", i);
    }
    return 0;
}
