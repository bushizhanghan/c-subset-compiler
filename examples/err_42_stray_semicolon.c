/* err_42_stray_semicolon.c
 * ---------------------------------------------------------------
 * 错误：if 的条件后面多了一个分号，把 if 变成了空语句。
 * 为什么错（教材概念）：C 的语法里 `if (cond) ;` 是完全合法的——
 *   分号是一条空语句，构成 if 的整个"then 分支"。于是条件成立时什么
 *   都不做，紧跟在后面的那块代码变成了**无条件执行**。
 *   教材讲"空语句"时专门警告过这个坑：`if (...)` 后面直接写分号，
 *   缩进看起来像是有分支，实际上分支是空的。
 *   本例中 max = a; 和 max = b; 都会执行，所以无论 a、b 谁大，
 *   max 永远是 b（后一次赋值覆盖前一次）。
 * 后果：能编译，gcc -Wall -Wextra 一声不响（它认为这是合法代码），
 *   属于"能跑、结果错、静态工具全放行"的典型。
 * 期望 csub 报什么：if 的条件后跟了空语句，其后的代码块不受条件控制。
 * 期望码：未实现
 * 分类：逻辑错误
 * ---------------------------------------------------------------
 */
int main() {
    int a = 5;
    int b = 10;
    int max = 0;
    if (a > b);                  /* ← 错在这：多了一个分号，if 的分支是空的 */
    {
        max = a;                 /* 无条件执行 */
    }
    if (b > a);                  /* ← 同一个错，第二处 */
    {
        max = b;                 /* 也无条件执行，覆盖上一行 */
    }
    printf("%d\n", max);
    return 0;
}
