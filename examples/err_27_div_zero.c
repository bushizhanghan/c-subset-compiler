/* err_27_div_zero.c
 * ---------------------------------------------------------------
 * 错误：除数为常量 0。
 * 为什么错（教材概念）：除法运算要求除数不为 0。教材在讲算术
 *   运算符时会注明"除数不能为 0"。运行时这是整数除零，在 x86
 *   上会触发 SIGFPE，程序直接被信号杀掉。
 * 期望 csub 报什么：E12 除数是常量 0。
 * ---------------------------------------------------------------
 */
int main() {
    int total = 10;
    int n = 0;
    int avg = total / 0;      /* ← 错在这：除数为 0 */
    printf("%d\n", avg);
    return 0;
}
