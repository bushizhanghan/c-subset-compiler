/* err_29_use_after_free.c
 * ---------------------------------------------------------------
 * 错误：free 之后继续通过同一个指针读写。
 * 为什么错（教材概念）：free(p) 只是把 p 指向的那块堆内存交还给分配器，
 *   p 这个变量本身的值没有变，仍然指着那块已经作废的内存。这种指针叫
 *   「悬垂指针（dangling pointer）」，是教材「动态内存分配」一章里
 *   最先强调的坑：free 之后必须立刻把指针置为 NULL，并且永不再解引用。
 *   那块内存可能已经被系统分配给别人，写它等于悄悄破坏别人的数据；
 *   也可能已经被回收，读它触发段错误。两种都极难排查。
 * 后果：能编译，常常还能"正常"跑几次，然后随机崩溃或算出乱数。
 * 期望 csub 报什么：free 之后使用已释放的指针（当前 csub 无对应诊断码）。
 * 期望码：未实现
 * 分类：指针生命周期
 * ---------------------------------------------------------------
 */
int main() {
    int *p = malloc(2 * sizeof(int));
    int i;
    for (i = 0; i < 2; i++) {
        p[i] = i * 10;
    }
    free(p);                     /* 内存已经交还给分配器 */
    printf("%d\n", p[0]);        /* ← 错在这：还在读这块已释放的内存 */
    free(p);                     /* 这里又碰了一次（本题只考上面的读） */
    return 0;
}
