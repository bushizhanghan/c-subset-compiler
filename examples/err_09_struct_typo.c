/* err_09_struct_typo.c
 * ---------------------------------------------------------------
 * 错误：结构体成员名拼错，把 num 写成 nma。
 * 为什么错（教材概念）：结构体成员必须严格按定义写。教材在讲
 *   结构体时会说明成员访问用 . 和 ->，成员名写错编译器直接报
 *   "no member named"。这是纯粹的笔误类错误，但在没有编辑器
 *   补全的情况下极其常见。
 * 期望 csub 报什么：E15 结构体没有该成员，并给出"是不是想写
 *   'num'？"的编辑距离建议。
 * ---------------------------------------------------------------
 */
struct Student {
    int num;
    char name[20];
    float score;
};

int main() {
    struct Student s;
    s.nma = 1001;             /* ← 错在这：应为 s.num */
    printf("%d\n", s.nma);
    return 0;
}
