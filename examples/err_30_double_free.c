/* err_30_double_free.c
 * ---------------------------------------------------------------
 * 错误：同一块堆内存被 free 两次。
 * 为什么错（教材概念）：free 的契约是「释放一块由 malloc/calloc/realloc
 *   返回、且当前仍然有效的内存」。第二次释放时这块内存已经不在分配器
 *   的"已分配"名单里了，分配器内部的空闲链表被破坏。
 *   教材讲 free 时反复强调"一个指针只能 free 一次"，
 *   并要求 free 后把指针置 0：置 0 之后 free(p) 是合法的空操作，
 *   这正好顺带解决了重复释放的问题——而本用例恰恰漏了这一步。
 * 后果：在多数分配器上不是当场报错，而是**下次 malloc 时**才崩，
 *   所以初学者会把锅归咎于毫无关系的那一行代码。
 * 期望 csub 报什么：同一个指针被重复释放，第二次 free 时内存已失效。
 * 期望码：未实现
 * 分类：指针生命周期
 * ---------------------------------------------------------------
 */
int main() {
    int *p = malloc(4 * sizeof(int));
    if (p == 0) {
        return 1;
    }
    p[0] = 1;
    p[1] = 2;
    free(p);
    /* ← 错在这：少了 p = 0; 于是下面第二次 free 的是同一块内存 */
    free(p);
    return 0;
}
