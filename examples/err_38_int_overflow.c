/* err_38_int_overflow.c
 * ---------------------------------------------------------------
 * 错误：int 加 1 越过了 int 的表示范围上界。
 * 为什么错（教材概念）：32 位有符号 int 的范围是
 *   -2147483648 .. 2147483647。2147483647 + 1 在数学上是 2147483648，
 *   但这个值 int 装不下，C 标准直接把这种有符号溢出定义为**未定义行为**，
 *   不是"回绕成负数"——回绕是很多教材的简化说法，实际编译器可以
 *   假定它不会发生，从而把相关判断优化掉。
 *   教材讲"数据类型与取值范围"时必然讲到这条边界：
 *   求和、阶乘、Fibonacci 是初学者最容易撞上溢出的三处。
 * 后果：能编译，gcc 默认也不警告（要 -ftrapv 或 UBSan 才抓得到），
 *   这是"能跑但结果是错的"最纯粹的形态。
 * 期望 csub 报什么：常量运算结果超出 int 表示范围，有符号整数溢出。
 * 期望码：未实现
 * 分类：整数溢出
 * ---------------------------------------------------------------
 */
int main() {
    int big = 2147483647;        /* INT_MAX：int 能表示的最大值 */
    int over = big + 1;          /* ← 错在这：有符号溢出，未定义行为 */
    printf("%d\n", over);        /* 实际会打印 -2147483648 */
    return 0;
}
