/* err_22_missing_return.c
 * ---------------------------------------------------------------
 * 错误：非 void 函数在某个分支上没有返回值。
 * 为什么错（教材概念）：函数只要有非 void 的返回类型，每条执行
 *   路径都必须 return 一个值。教材讲函数时会说明"返回值通过
 *   return 语句带回，缺少 return 时返回值是不确定的"。
 * 后果：调用方拿到的返回值是寄存器里的垃圾值。
 * 期望 csub 报什么：一条"函数可能没有返回值"的警告。
 *   csub 目前只对 main 做 W8 检查，普通函数没有覆盖，
 *   预期漏报（这是合理缺口，main 的 W8 是通用版的一个子集）。
 * ---------------------------------------------------------------
 */
int sign(int x) {
    if (x > 0) {
        return 1;
    }
    else if (x < 0) {
        return -1;
    }
    /* ← 错在这：x == 0 时没有 return 0 */
}

int main() {
    printf("%d\n", sign(0));
    return 0;
}
