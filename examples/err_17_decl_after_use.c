/* err_17_decl_after_use.c
 * ---------------------------------------------------------------
 * 错误：在变量声明之前就使用它（C89 规则下是错误，C99 允许但
 *   很多教材仍按 C89 教）。
 * 为什么错（教材概念）："先定义后使用"。教材讲变量作用域时
 *   说明：标识符从声明处开始生效，之前不可见。
 * 后果：C99 编译器给 warning，C89 编译器给 error。
 * 期望 csub 报什么：E1 使用了未声明的变量 'a'。
 *   csub 是单遍收集+检查，作用域模型按声明顺序，应该能检出。
 * ---------------------------------------------------------------
 */
int main() {
    a = 5;                    /* ← 错在这：a 在下一行才声明 */
    int a;
    printf("%d\n", a);
    return 0;
}
