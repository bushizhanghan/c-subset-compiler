/* err_16_string_no_terminator.c
 * ---------------------------------------------------------------
 * 错误：手工给字符数组逐元素赋值，但忘了写结束符 '\0'。
 * 为什么错（教材概念）：C 语言的字符串以 '\0' 结尾。教材讲字符
 *   数组与字符串时会强调：用 %s 打印的字符数组必须以 '\0' 结束，
 *   否则 printf 会一直往后读内存直到碰巧遇到一个 0。
 * 后果：printf("%s") 打印出乱码甚至崩溃。
 * 期望 csub 报什么：一条"字符数组可能缺少字符串结束符"的警告。
 *   目前 csub 没有这条检查，预期漏报。
 * ---------------------------------------------------------------
 */
int main() {
    char s[3];
    s[0] = 'a';
    s[1] = 'b';
    s[2] = 'c';               /* ← 错在这：应为 s[2] = '\0' */
    printf("%s\n", s);
    return 0;
}
