/* err_35_string_missing_nul.c
 * ---------------------------------------------------------------
 * 错误：把字符数组的每个字节都写满字符，没有留 '\0' 的位置。
 * 为什么错（教材概念）：C 的字符串不是一种类型，而是"以 '\0' 结尾的
 *   字符序列"这个约定。printf("%s") / strlen / strcpy 全都靠扫描 '\0'
 *   来判断字符串在哪结束。数组长度 5 就只能装 4 个可见字符 + 1 个 '\0'，
 *   这正是教材强调"字符数组至少要开 n+1"的原因。
 *   本用例写满了 5 个字符，数组里没有结束符，printf 会一直往后读，
 *   直到在栈上随便撞见一个值为 0 的字节才停——那已经是别人的内存了。
 * 为什么和 err_16 不同：err_16 是"少写一个字符"，本用例是"写满但不留
 *   结束符"，两者都是 overrun，但成因相反：一个是漏写，一个是没留位。
 * 后果：能编译，printf 打印出一串乱码外加越界读取，可能直接崩。
 * 期望 csub 报什么：字符数组被逐个写满但没有 '\0'，缺少字符串结束符。
 * 期望码：未实现
 * 分类：数组与字符串
 * ---------------------------------------------------------------
 */
#include <stdio.h>
int main() {
    char word[5];
    /* ← 错在这：5 个字节全填了可见字符，没有位置放 '\0' */
    word[0] = 'h';
    word[1] = 'e';
    word[2] = 'l';
    word[3] = 'l';
    word[4] = 'o';
    printf("%s\n", word);        /* 越界读到下一个 0 字节才停 */
    return 0;
}
