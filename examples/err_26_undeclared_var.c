/* err_26_undeclared_var.c
 * ---------------------------------------------------------------
 * 错误：使用了一个从未声明的变量（最典型的是把已声明的 count
 *   拼成了 conut）。
 * 为什么错（教材概念）：标识符必须先声明后使用。教材在"变量"
 *   一节说过：编译系统需要根据声明来分配存储空间并确定类型，
 *   没声明就没法分配。
 * 后果：编译报 error: 'conut' undeclared。
 * 期望 csub 报什么：E1 使用了未声明的变量 'conut'。
 * ---------------------------------------------------------------
 */
int main() {
    int count = 0;
    conut = conut + 1;        /* ← 错在这：应为 count */
    printf("%d\n", count);
    return 0;
}
