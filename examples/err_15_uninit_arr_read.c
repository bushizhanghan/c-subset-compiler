/* err_15_uninit_arr_read.c
 * ---------------------------------------------------------------
 * 错误：数组声明后没有初始化任何元素就直接读取打印。
 * 为什么错（教材概念）：局部数组不会自动清零。教材在讲数组时
 *   提醒"定义数组后如果不初始化，元素的值是不确定的"。
 * 后果：打印出随机数。
 * 期望 csub 报什么：W21 读取从未赋值的数组元素。
 *   注意：这是 csub 已知的有意取舍——数组声明时直接标记
 *   initialized=True，避免"整块被函数写入"的场景误报。
 *   因此本例预期漏报，且这个取舍是合理的（见 README 已知边界）。
 * ---------------------------------------------------------------
 */
int main() {
    int a[4];                 /* 没有初始化任何一个元素 */
    printf("%d\n", a[2]);     /* ← 错在这：读了一个垃圾值 */
    return 0;
}
