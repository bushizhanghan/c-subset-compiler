/* err_06_float_eq.c
 * ---------------------------------------------------------------
 * 错误：用 == 直接比较两个浮点数是否相等。
 * 为什么错（教材概念）：IEEE 754 浮点数有精度误差，0.1 + 0.2 的
 *   结果并不精确等于 0.3。教材在"实型数据"一节会提醒浮点比较
 *   要用误差范围判断，如 fabs(x - y) < 1e-6。
 * 后果：看起来一定成立的判断失败，循环一次都不执行。
 * 期望 csub 报什么：W5 浮点数与常量/变量直接比较的精度风险警告。
 *   csub 的 W5 已覆盖"条件表达式整体是浮点"的情况（如 if (f)），
 *   但 `a == b` 这种两边都是 float 的关系运算目前可能不报。
 * ---------------------------------------------------------------
 */
int main() {
    float a = 0.1;
    float b = 0.2;
    float c = 0.3;
    if (a + b == c) {         /* ← 错在这：应为 fabs(a+b-c) < 1e-6 */
        printf("equal\n");
    }
    return 0;
}
