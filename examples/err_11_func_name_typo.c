/* err_11_func_name_typo.c
 * ---------------------------------------------------------------
 * 错误：调用了一个拼错名字的函数（prinf 而不是 printf）。
 * 为什么错（教材概念）：标识符必须前后一致。拼错库函数名时，
 *   编译器会先假设它是"隐式声明"，链接期才报 undefined reference
 *   ——报错信息离出错点很远，初学者往往看不懂。
 * 期望 csub 报什么：E5 调用了未声明的函数 'prinf'。
 *   注意：csub 有一条"首字母大写的函数名当作外部函数"的容忍
 *   规则，prinf 全小写不在容忍范围内，应该能报出来。
 * ---------------------------------------------------------------
 */
int main() {
    prinf("hello\n");         /* ← 错在这：应为 printf */
    return 0;
}
