/* err_08_ptr_uninit_deref.c
 * ---------------------------------------------------------------
 * 错误：指针 p 没有指向任何东西就直接解引用写入。
 * 为什么错（教材概念）：指针变量本身也是一个变量，声明后里面是
 *   垃圾地址。教材讲指针时会强调"指针必须先赋值再使用"，
 *   野指针解引用是段错误的第一大来源。
 * 后果：运行时直接 Segmentation fault。
 * 期望 csub 报什么：E2 对未初始化的指针做解引用。
 * ---------------------------------------------------------------
 */
int main() {
    int *p;                   /* ← 错在这：没有 p = &x 或 malloc */
    *p = 5;                   /* 往野指针指向的地址写数据 */
    printf("%d\n", *p);
    return 0;
}
