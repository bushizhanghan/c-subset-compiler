/* err_36_block_scope_escape.c
 * ---------------------------------------------------------------
 * 错误：把内层块里定义的变量地址带出了块作用域。
 * 为什么错（教材概念）：教材讲"局部变量的作用域"时说，块内定义的变量
 *   只在这个块里可见；但更关键也更常被忽略的一点是——它的**生存期**
 *   也在块结束时就终结了。本例里 p 在块外仍然保存着 &inner 这个值，
 *   编译器不会拦（p 自己活着），可它指的那 4 字节已经作废。
 *   这是 err_31（返回局部变量地址）的块级版本，也是学生写
 *   "在 if / for 里临时定义再拿出来用"时的高频错误。
 * 后果：能编译，*p 读到的是块结束后别人写进那块栈的内容。
 * 期望 csub 报什么：块作用域内变量的地址被带出该块。
 * 期望码：W20
 * 分类：作用域与生命周期
 * ---------------------------------------------------------------
 */
int main() {
    int *p = 0;
    {
        int inner = 7;
        p = &inner;              /* ← 错在这：inner 在下面这个 } 就死了 */
    }
    printf("%d\n", *p);          /* p 逃出了块，但它指的对象没有 */
    return 0;
}
