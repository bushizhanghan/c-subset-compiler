/* err_31_return_local_addr.c
 * ---------------------------------------------------------------
 * 错误：函数返回了局部变量的地址。
 * 为什么错（教材概念）：函数的局部变量存放在**栈帧**里，函数一 return，
 *   栈帧就被回收，下一个被调用的函数会立刻把它覆盖掉。所以 &local
 *   这个地址在函数返回的那一刻就失效了，外面拿到的是一个指向已作废
 *   栈内存的野指针。教材讲"函数返回指针"时把这条列为头号禁区：
 *   要返回的地址必须在函数返回后依然有效——只能是全局变量、静态变量
 *   或 malloc 出来的堆内存。
 * 后果：编译器通常只给一句 -Wreturn-local-addr 警告，程序照跑不误，
 *   然后打印出一个"看起来像真的"的垃圾值，排查成本极高。
 * 期望 csub 报什么：W9 返回了局部变量的地址，该地址在函数返回后失效。
 * 期望码：W9
 * 分类：指针生命周期
 * ---------------------------------------------------------------
 */
int *pick(void) {
    int local = 42;
    return &local;               /* ← 错在这：local 随函数返回一起消失 */
}

int main() {
    int *p = pick();
    printf("%d\n", *p);          /* 读到的是别人的栈帧 */
    return 0;
}
