/* err_21_unused_var.c
 * ---------------------------------------------------------------
 * 错误：声明了一个变量却从没使用过。
 * 为什么错（教材概念）：这本身不是逻辑错误，但它是"抄错变量名"
 *   的强烈信号——更常见的情况是本来想用 total，结果写成了
 *   sum，导致 total 一直没被碰过。教材在代码规范里要求
 *   "不要定义用不到的变量"。
 * 后果：不一定有运行期问题，但几乎总意味着别处有个笔误。
 * 期望 csub 报什么：W6 变量声明后从未使用。
 * ---------------------------------------------------------------
 */
int main() {
    int sum = 0;
    int total = 0;            /* ← 可疑：声明后从未使用，疑似想写的是 sum */
    int i;
    for (i = 1; i <= 5; i++) {
        sum = sum + i;
    }
    printf("%d\n", sum);
    return 0;
}
