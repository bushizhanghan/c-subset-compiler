/* err_23_scope_confusion.c
 * ---------------------------------------------------------------
 * 错误：在 for 循环体内声明的变量，循环外还想用。
 * 为什么错（教材概念）：变量的作用域。花括号内声明的局部变量
 *   只在该块内有效，出了块就被销毁。教材在"局部变量与全局
 *   变量"一节讲过：不同作用域内可以有同名变量，互不干扰。
 * 后果：C99 下编译报"use of undeclared identifier"，C89 下连
 *   编译都过不去（C89 不允许在语句中间声明）。
 * 期望 csub 报什么：E1 使用了未声明的变量 'j'。
 * ---------------------------------------------------------------
 */
int main() {
    int i;
    for (i = 0; i < 3; i++) {
        int j = i * 2;        /* j 只在循环体内有效 */
    }
    printf("%d\n", j);        /* ← 错在这：j 已经离开作用域 */
    return 0;
}
