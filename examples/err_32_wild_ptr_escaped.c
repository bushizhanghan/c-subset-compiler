/* err_32_wild_ptr_escaped.c
 * ---------------------------------------------------------------
 * 错误：把局部变量的地址存进全局指针，函数返回后这个指针就成了野指针。
 * 为什么错（教材概念）：这是 err_31 的"间接版"，也是野指针最常见的成因。
 *   局部变量 inner 的生存期（storage duration）严格限制在 setup 的栈帧
 *   里；函数一返回，栈帧被回收，全局指针 g 指向的地址可能已经被
 *   printf 自己的栈帧占用。
 *   教材区分"变量作用域（scope）"与"变量生存期（lifetime）"时，
 *   用的正是这个例子：名字 g 在整个文件里都可见，但它指向的对象
 *   早就没了——可见不等于有效。
 * 后果：能编译，结果依赖运行时的栈布局，换个编译器或加一行 printf
 *   就可能变一个结果。这类 bug 不能靠"多跑几次"发现。
 * 期望 csub 报什么：把局部变量的地址赋给了生存期更长的指针。
 * 期望码：未实现
 * 分类：指针生命周期
 * ---------------------------------------------------------------
 */
#include <stdlib.h>
#include <stdio.h>
int *g = 0;                      /* 全局指针，活到最后 */

void setup(void) {
    int inner = 7;
    g = &inner;                  /* ← 错在这：inner 随 setup 返回一起消失 */
}

int main() {
    setup();
    printf("%d\n", *g);          /* g 还叫 g，但它指的东西已经不在了 */
    return 0;
}
