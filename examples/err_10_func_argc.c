/* err_10_func_argc.c
 * ---------------------------------------------------------------
 * 错误：调用自己写的函数时少传了一个参数。
 * 为什么错（教材概念）：函数调用的实参个数必须与形参一致，
 *   这是教材"函数的参数"一节的基本要求。少传参数时，被调函数
 *   里读到的第二个形参是垃圾值。
 * 后果：结果随机错，且编译期只有 warning。
 * 期望 csub 报什么：E4 函数参数个数不符（2 个形参，传了 1 个）。
 * ---------------------------------------------------------------
 */
int max2(int a, int b) {
    if (a > b) {
        return a;
    }
    return b;
}

int main() {
    int r = max2(10);         /* ← 错在这：应为 max2(10, 20) */
    printf("%d\n", r);
    return 0;
}
