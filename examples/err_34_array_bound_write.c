/* err_34_array_bound_write.c
 * ---------------------------------------------------------------
 * 错误：for 循环条件写成 i <= n，向 n+1 个元素的数组写了第 n+1 个元素。
 * 为什么错（教材概念）：C 数组下标从 0 开始，长度 n 的数组合法下标是
 *   0..n-1。教材讲"数组元素引用"时反复强调上界是 n-1；
 *   这里 a[5] 落在 a[4] 之后的那 4 个字节上——那块内存属于别的变量。
 *   这类错叫 off-by-one（差一错误），是最经典的循环边界错误。
 * 为什么单独立一个用例：err_03 的下标是常量 a[5]，能被常量折叠抓到；
 *   本用例的下标是循环变量 i，只有在"循环变量 → 取值区间 → 与数组长度
 *   比较"这条推理链上才能发现，考的是 csub 有没有区间分析。
 * 后果：能编译，写坏相邻变量，甚至可以正常跑很久才崩。
 * 期望 csub 报什么：循环上界使下标达到数组长度，越界写。
 * 期望码：W16
 * 分类：数组与字符串
 * ---------------------------------------------------------------
 */
int main() {
    int a[5];
    int i;
    for (i = 0; i <= 5; i++) {   /* ← 错在这：应为 i < 5 */
        a[i] = i * i;            /* i == 5 时写到 a[5]，越界 1 个元素 */
    }
    printf("%d\n", a[4]);
    return 0;
}
