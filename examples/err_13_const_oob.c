/* err_13_const_oob.c
 * ---------------------------------------------------------------
 * 错误：用常量下标直接越界访问。
 * 为什么错（教材概念）：数组下标从 0 开始，长度为 3 的数组只有
 *   0、1、2 三个合法下标。教材在"一维数组"一节给出过示意：
 *   a[3] 是第 4 个元素，而数组只有 3 个。
 * 后果：读到相邻内存，输出垃圾值。
 * 期望 csub 报什么：E13 数组下标 3 越界（长度是 3）。
 * ---------------------------------------------------------------
 */
int main() {
    int a[3];
    a[0] = 1;
    a[1] = 2;
    a[2] = 3;
    printf("%d\n", a[3]);     /* ← 错在这：合法下标只到 2 */
    return 0;
}
