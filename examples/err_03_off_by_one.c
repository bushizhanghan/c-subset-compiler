/* err_03_off_by_one.c
 * ---------------------------------------------------------------
 * 错误：循环条件写成 i <= 5，数组只有 5 个元素（合法下标 0..4）。
 * 为什么错（教材概念）："循环边界"是数组章节的经典陷阱。数组
 *   长度是 5 时，最后一个元素的下标是 4，因为下标从 0 开始。
 *   教材里反复强调 `i < n` 而不是 `i <= n`。
 * 后果：arr[5] 是越界写，会踩坏相邻内存（本程序里会改掉别的
 *   局部变量），表现为"结果莫名奇妙地变大"。
 * 期望 csub 报什么：E13 数组下标越界。注意这里下标是变量 i，
 *   csub 的 E13 只查常量下标，所以本例很可能只报 W5（条件恒真
 *   之类）或完全不报——这正是要记录的漏报。
 * ---------------------------------------------------------------
 */
int main() {
    int arr[5];
    int i;
    for (i = 0; i <= 5; i++) {   /* ← 错在这：<= 应为 < */
        arr[i] = i * 2;          /* i == 5 时越界写 */
    }
    printf("%d\n", arr[4]);
    return 0;
}
