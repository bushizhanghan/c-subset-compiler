/* err_04_loop_never_advance.c
 * ---------------------------------------------------------------
 * 错误：while 循环体里忘了写 i = i + 1，循环变量永不前进。
 * 为什么错（教材概念）："循环三要素"（初值、条件、增量）里少了
 *   增量，循环条件永远为真。这是死循环最典型的成因，教材在讲
 *   while 时会专门提醒"务必在循环体内改变循环变量的值"。
 * 后果：程序卡死，或者（如果编译器优化掉看起来无副作用的循环）
 *   直接跳过。
 * 期望 csub 报什么：一条"while 条件恒为真 / 循环变量未更新"的
 *   死循环倾向警告。目前 csub 没有这条检查，预期漏报。
 * ---------------------------------------------------------------
 */
int main() {
    int i = 0;
    int total = 0;
    while (i < 10) {
        total = total + i;
        /* ← 错在这：循环体里没有 i = i + 1 */
    }
    printf("%d\n", total);
    return 0;
}
