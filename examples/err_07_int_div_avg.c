/* err_07_int_div_avg.c
 * ---------------------------------------------------------------
 * 错误：求平均值时两个整数相除，小数部分被丢掉。
 * 为什么错（教材概念）：整数除法截断取整。教材在"整型数据"一节
 *   明确写了 5/2 的结果是 2 而不是 2.5。求平均必须先转 float，
 *   或写 1.0 * sum / n。
 * 后果：算出来的平均值偏小，且偏小的量随数据变化，很难发现。
 * 期望 csub 报什么：W3 整数相除会丢弃小数部分。
 * ---------------------------------------------------------------
 */
int main() {
    int sum = 7;
    int n = 2;
    int avg = sum / n;        /* ← 错在这：应为 (float)sum / n 或 1.0*sum/n */
    printf("%d\n", avg);      /* 打印 3，期望 3.5 */
    return 0;
}
