/* err_14_2d_array_mixed.c
 * ---------------------------------------------------------------
 * 错误：把二维数组的两个维度搞混，用一维的下标范围去索引第二维。
 * 为什么错（教材概念）：二维数组 a[2][3] 的含义是"2 行 3 列"，
 *   第一维的下标范围 0..1，第二维的下标范围 0..2。行和列的
 *   边界必须分别记清，教材在"二维数组"一节有明确的行列示意。
 * 后果：a[0][5] 落在同一行的内存之后，越界读写。
 * 期望 csub 报什么：E13 数组下标越界（第二维长度是 3，用了 5）。
 *   csub 对 `a[0][5]` 这种完整常量链是支持的，应该能检出。
 * ---------------------------------------------------------------
 */
int main() {
    int a[2][3];
    a[0][0] = 1;
    a[0][1] = 2;
    a[0][5] = 3;              /* ← 错在这：第二维长度是 3，合法下标 0..2 */
    printf("%d\n", a[0][0]);
    return 0;
}
