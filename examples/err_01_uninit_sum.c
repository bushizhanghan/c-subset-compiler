/* err_01_uninit_sum.c
 * ---------------------------------------------------------------
 * 错误：累加变量 sum 没有赋初值。
 * 为什么错（教材概念）：局部变量不会自动清零。C 语言里只有全局变量
 *   和 static 变量有默认零初始化，函数内的局部变量值是"上一次
 *   占用这块内存留下的垃圾"。教材《C程序设计》里专门有一节讲
 *   "变量必须先定义后使用，且定义时最好初始化"。
 * 这段代码能编译通过（gcc 只在 -Wall 下给 warning），但每次运行
 * 结果都不一样——这是初学者最常遇到且最难自查的 bug。
 * 期望 csub 报什么：E2 使用未初始化的变量 'sum'。
 * ---------------------------------------------------------------
 */
int main() {
    int i;
    int sum;                 /* ← 错在这：没有 = 0 */
    for (i = 1; i <= 10; i++) {
        sum = sum + i;       /* 读了一个垃圾值再往上加 */
    }
    printf("%d\n", sum);
    return 0;
}
