/* err_40_infinite_growth.c
 * ---------------------------------------------------------------
 * 错误：for 循环的初值已经满足条件，增量方向却与条件相反。
 * 为什么错（教材概念）：for 循环的三段是"初始化 / 继续条件 / 每轮之后的
 *   增量"。循环能终止的前提是**增量让条件逐渐不成立**。
 *   本例初值 i = 10、条件 i > 0、增量 i++，i 越跑越大，条件永远为真。
 *   教材讲 for 语句时把这三段的方向一致性列成检查清单：
 *   "条件用 > 还是 <，增量就必须用 ++ 还是 --"，两者必须配对。
 * 为什么和 err_28 分开：err_28 是 i < 10 配 i--（从下往上跑却在下减），
 *   本用例是 i > 0 配 i++（从上往下跑却在上加），方向判断的推理方向相反，
 *   覆盖不同的实现路径。
 * 后果：能编译，跑起来死循环，学生会以为程序"卡住了"。
 * 期望 csub 报什么：循环增量方向与终止条件相反，循环不会结束。
 * 期望码：未实现
 * 分类：逻辑错误
 * ---------------------------------------------------------------
 */
int main() {
    int sum = 0;
    int i;
    for (i = 10; i > 0; i++) {   /* ← 错在这：条件在变小方向，增量却在变大 */
        sum = sum + i;
    }
    printf("%d\n", sum);
    return 0;
}
