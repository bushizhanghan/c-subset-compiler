/* err_02_scan_missing_amp.c
 * ---------------------------------------------------------------
 * 错误：scanf 的第二个参数忘了写取地址符 &。
 * 为什么错（教材概念）：C 语言是值传递，scanf 需要的是变量的地址
 *   才能把输入写进去。教材讲 scanf 时都会强调"输入项必须是地址
 *   表达式"，这一条是初学者错误率最高的写法之一。少了 & 时
 *   scanf 会把 v 当前的值（垃圾值）当指针去写，直接段错误。
 * 期望 csub 报什么：E2 使用未初始化的变量 'v'（把 v 当实参传入，
 *   相当于读取了一个未初始化的值）；理想情况下还应提示"scanf
 *   的输入参数需要 &"。
 * ---------------------------------------------------------------
 */
int main() {
    int v;
    scanf("%d", v);          /* ← 错在这：少了 &，应为 scanf("%d", &v) */
    printf("%d\n", v);
    return 0;
}
