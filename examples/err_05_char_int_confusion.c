/* err_05_char_int_confusion.c
 * ---------------------------------------------------------------
 * 错误：把字符常量 "A"（字符串）赋给 char 变量。
 * 为什么错（教材概念）：字符常量用单引号 'A'，字符串用双引号
 *   "A"。字符串在 C 里是"指向首字符的指针"，不是单个字符值。
 *   教材在"字符常量与字符串"一节专门对比过这两者。
 * 后果：编译期是 warning（C++ 里直接 error），运行时会报
 *   "assignment makes integer from pointer without a cast"，
 *   实际赋进去的是字符串首地址的低位字节。
 * 期望 csub 报什么：一条类型不兼容警告（把 char* 赋给 char）。
 *   目前 csub 的类型推导里 Str 一律返回 "char*"，而赋值的
 *   兼容性检查只覆盖 float→int（W4），预期漏报。
 * ---------------------------------------------------------------
 */
int main() {
    char c;
    c = "A";                  /* ← 错在这：应为 'A' */
    printf("%c\n", c);
    return 0;
}
