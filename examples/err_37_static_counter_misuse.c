/* err_37_static_counter_misuse.c
 * ---------------------------------------------------------------
 * 错误：本想用一个普通局部变量在两次调用之间独立计数，却写成了 static。
 * 为什么错（教材概念）：static 修饰局部变量时改变了它的**存储期**：
 *   从"函数调用期间"变成"整个程序运行期间"，并且只初始化一次。
 *   于是 n 的值在 call_count 返回后仍然保留，第二次调用从 1 开始累加，
 *   输出 1 2 而不是题意的 1 1。
 *   教材讲"变量的存储类别"（auto / static / register / extern）时，
 *   正是用这个反例说明：static 局部变量不是"函数内的全局变量"这么简单，
 *   它会让函数变成**有状态的、不可重入的**。
 * 后果：能编译，结果只在"多次调用"时才暴露；单次调试看不出问题。
 *   在递归函数里把局部变量写成 static，还会让各层递归共享同一份数据，
 *   这是同一类错误的更严重形态。
 * 期望 csub 报什么：static 局部变量跨调用保留状态，可能不是本意。
 * 期望码：未实现
 * 分类：作用域与生命周期
 * ---------------------------------------------------------------
 */
#include <stdio.h>
int call_count(void) {
    static int n = 0;            /* ← 错在这：只想当普通计数器，不该加 static */
    n = n + 1;
    return n;
}

int main() {
    int a = call_count();        /* 期望 1，实际 1 */
    int b = call_count();        /* 期望 1，实际 2 —— static 记住上一次的值 */
    printf("%d %d\n", a, b);
    return 0;
}
