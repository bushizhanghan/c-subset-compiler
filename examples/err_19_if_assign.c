/* err_19_if_assign.c
 * ---------------------------------------------------------------
 * 错误：if 条件里把比较 == 写成了赋值 =。
 * 为什么错（教材概念）：= 是赋值运算符，== 才是关系运算符。
 *   教材在"关系运算符与表达式"一节专门把这两个放在一起对比，
 *   并指出 if (a = 1) 永远为真。
 * 后果：if 分支无条件进入，程序逻辑整体跑偏。
 * 期望 csub 报什么：W5 if 的条件里用了赋值 =，通常是想写比较 ==。
 * ---------------------------------------------------------------
 */
int main() {
    int x = 0;
    if (x = 10) {             /* ← 错在这：应为 if (x == 10) */
        printf("x is ten\n");
    }
    return 0;
}
