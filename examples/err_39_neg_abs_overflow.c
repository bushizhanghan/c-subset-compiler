/* err_39_neg_abs_overflow.c
 * ---------------------------------------------------------------
 * 错误：对 int 的最小值取绝对值。
 * 为什么错（教材概念）：补码表示是不对称的——int 的范围是
 *   -2147483648 .. 2147483647，负数的个数比正数多一个。
 *   所以 |-2147483648| = 2147483648 在 int 里根本表示不出来，
 *   abs() 返回时结果溢出，标准规定这是未定义行为，glibc 的实际实现
 *   会把原值原样返回，于是 abs() 的结果仍然是负数。
 *   教材讲"补码"与"为什么负数比正数多一个"时，这就是标准例题；
 *   也解释了为什么 <stdlib.h> 里 abs 的返回类型是 int 而不是
 *   "一定能装下绝对值"的类型——用 labs / llabs / fabs 才安全。
 * 后果：能编译，abs 之后的值仍然是负数，下游所有"绝对值一定非负"
 *   的假设全部失效。这是数值库里出了名的坑。
 * 期望 csub 报什么：对 int 最小值取绝对值会溢出。
 * 期望码：未实现
 * 分类：整数溢出
 * ---------------------------------------------------------------
 */
#include <stdlib.h>
#include <stdio.h>
int main() {
    int neg = -2147483648;       /* int 能表示的唯一下界值 */
    int mag = abs(neg);          /* ← 错在这：2147483648 装不进 int */
    if (mag < 0) {
        printf("abs returned negative\n");   /* 这一行真的会执行 */
    }
    printf("%d\n", mag);
    return 0;
}
