/* err_33_strcpy_overflow.c
 * ---------------------------------------------------------------
 * 错误：strcpy 把 6 个字符的字符串拷进只有 4 字节的数组。
 * 为什么错（教材概念）：strcpy 不做任何长度检查，它只认 'a'..'f' 之后
 *   的那个 '\0'，把它连同前面 6 个字符一起搬过去，总共写入 7 字节。
 *   目标数组 s 只有 4 字节，多出来的 3 字节会覆盖 s 之后的栈内存
 *   （相邻的局部变量、保存的返回地址）。
 *   教材"字符数组与字符串"一节的标准结论：**strcpy 是缓冲区溢出
 *   的头号来源**，安全写法是 strncpy 或 snprintf，并且要自己补 '\0'。
 * 后果：这是 CVE 里出现次数最多的一类漏洞（栈溢出），
 *   在演示程序里表现为"变量莫名其妙被改了"或直接段错误。
 * 期望 csub 报什么：常量字符串长度超过目标数组容量，会越界写。
 * 期望码：未实现
 * 分类：数组与字符串
 * ---------------------------------------------------------------
 */
int main() {
    char s[4];
    strcpy(s, "abcdef");         /* ← 错在这：源串 6 字符 + 1 个 '\0' = 7 字节 */
    printf("%s\n", s);
    return 0;
}
