/* err_20_pass_array_by_index.c
 * ---------------------------------------------------------------
 * 错误：把数组当普通变量传给形参为指针的函数，形参里又按
 *   "数组长度"去遍历，实际传进去的是数组首元素的值。
 * 为什么错（教材概念）：数组名作为实参时传递的是首地址，
 *   形参写成 int arr[] 或 int *arr；但如果形参是 int（按值），
 *   传进去的就只是 a[0] 这一个整数，后续所有元素都拿不到。
 *   教材在"数组作函数参数"一节强调"形参数组名 = 实参数组名，
 *   传递的是地址"。
 * 后果：函数里遍历的是一个垃圾地址，行为完全错误。
 * 期望 csub 报什么：一条"把数组传给非指针形参"的类型不兼容
 *   警告。目前 csub 的实参检查只数个数（E4），不查类型，
 *   预期漏报。
 * ---------------------------------------------------------------
 */
int sum_all(int v) {          /* ← 错在这：应为 int sum_all(int *v, int n) */
    int i;
    int s = 0;
    for (i = 0; i < 5; i++) {
        s = s + v;            /* 对一个整数 v 反复累加 */
    }
    return s;
}

int main() {
    int a[5] = {1, 2, 3, 4, 5};
    printf("%d\n", sum_all(a));   /* 传的是首地址，被当成一个 int */
    return 0;
}
